columns_to_fill = ['type','listed_in','title','director','country', 'release_year']

for col in columns_to_fill:
    netflix_cleaned[col] = netflix_cleaned[col].astype(str).fillna('unknown')

def clean_data(x):
    return str.lower(x.replace(" ", ""))

netflix_cleaned['cleaned_director'] = netflix_cleaned['director'].apply(clean_data)
netflix_cleaned['cleaned_country'] = netflix_cleaned['country'].apply(clean_data)

def clean_categories(x):
    return " ".join([clean_data(cat) for cat in x.split(',')])

netflix_cleaned['cleaned_listed_in'] = netflix_cleaned['listed_in'].apply(clean_categories)

netflix_cleaned['advanced_metadata'] = (
    netflix_cleaned['cleaned_listed_in'] + " " + netflix_cleaned['cleaned_listed_in'] + " " +  # Double weight for genres
    netflix_cleaned['cleaned_director'] + " " + netflix_cleaned['cleaned_director'] + " " +    # Double weight for directors
    netflix_cleaned['cleaned_country'] + " " +
    netflix_cleaned['release_year'].astype(str) + " " +
    netflix_cleaned['title'].str.lower()
)

tfidf = TfidfVectorizer(stop_words='english')
tfidf_matrix = tfidf.fit_transform(netflix_cleaned['advanced_metadata'])
cosine_sim = cosine_similarity(tfidf_matrix, tfidf_matrix)

indices = pd.Series(netflix_cleaned.index, index=netflix_cleaned['title']).drop_duplicates()

def get_advanced_recommendations(title, content_type_filter=None, num_recommendations=5):
    if title not in indices:
        return f"Title '{title}' not found in the dataset."

    idx = indices[title]

    sim_scores = list(enumerate(cosine_sim[idx]))

    sim_scores = sorted(sim_scores, key=lambda x: x[1], reverse=True)

    final_indices = []
    for i, score in sim_scores:

        if i == idx:
            continue

        if content_type_filter and netflix_cleaned.iloc[i]['type'] != content_type_filter:
            continue

        final_indices.append(i)


        if len(final_indices) == num_recommendations:
            break

    return netflix_cleaned[['title', 'type', 'director', 'country', 'listed_in']].iloc[final_indices]

