"""*** Task 5 ***"""

features = ['title', 'director', 'country', 'rating', 'release_year']
X = netflix_cleaned[features].copy()
y = netflix_cleaned['type'].astype(str)

X['release_year'] = X['release_year'].astype(int)
X['rating'] = X['rating'].astype(str)

"""*** Furhter splitting the data into test and train ***"""

X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.20, random_state=42, stratify=y
)

"""**** Building a preprocessing pipeline ****"""

preprocessor = ColumnTransformer(
    transformers=[
        ('title_tfidf', TfidfVectorizer(max_features=1000, stop_words='english'), 'title'),
        ('director_tfidf', TfidfVectorizer(max_features=500), 'director'),
        ('cat_ohe', OneHotEncoder(handle_unknown='ignore'), ['country', 'rating']),
        ('num_scaler', StandardScaler(), ['release_year'])
    ]
)

"""*** Trainig our model ***"""

model_pipeline = Pipeline(steps=[
    ('preprocessor', preprocessor),
    ('classifier', RandomForestClassifier(n_estimators=150, random_state=42, n_jobs=-1))
])

print("Training model...")
model_pipeline.fit(X_train, y_train)

"""*** Predicting the outcomes ***"""

y_pred = model_pipeline.predict(X_test)
y_proba = model_pipeline.predict_proba(X_test)[:, 1]

"""*** Evaluating model performance and accuracy ***"""

test_accuracy = accuracy_score(y_test, y_pred)
roc_auc = roc_auc_score((y_test == 'TV Show').astype(int), y_proba)

"""*** Checking for overfitting using 5 fold cross validation ***"""

cv_scores = cross_val_score(model_pipeline, X_train, y_train, cv=5, scoring='accuracy', n_jobs=-1)

print("\n" + "="*45)
print("           MODEL EVALUATION SUMMARY          ")
print("="*45)
print(f"Test Set Accuracy       : {test_accuracy * 100:.2f}%")
print(f"5-Fold CV Mean Accuracy : {cv_scores.mean() * 100:.2f}% (+/- {cv_scores.std() * 100:.2f}%)")
print(f"ROC-AUC Score           : {roc_auc:.4f}")
print("="*45 + "\n")

print("Detailed Classification Report:")

